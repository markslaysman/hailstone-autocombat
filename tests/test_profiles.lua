local profiles = require('lib.profiles')

case('profiles: old config remains the default file', function()
  local base = 'autocombat/Triune_Chad.lua'
  eq(profiles.settings_path(base, 'default'), base, 'original filename unchanged')
  eq(profiles.manifest_path(base), 'autocombat/Triune_Chad__profiles.lua', 'manifest beside config')
  eq(profiles.settings_path(base, 'Rift'), 'autocombat/Triune_Chad__profile_rift.lua', 'named file')
  local empty = profiles.repair(nil)
  eq(empty.active, 'default', 'default selected on migration')
  eq(#empty.names, 1, 'one profile when no manifest')
end)

case('profiles: name validation protects filesystem paths', function()
  eq(profiles.name('Rift_23'), 'rift_23', 'case normalized')
  eq(profiles.name('HUNTER-SOLO'), 'hunter-solo', 'hyphen allowed')
  for _, name in ipairs({ '../bad', 'hunter/solo', 'with space', 'dot.lua', '', ('x'):rep(33) }) do
    eq(profiles.name(name), nil, 'rejected unsafe name ' .. name)
  end
  eq(profiles.name(123), nil, 'non-string rejected')
end)

case('profiles: manifest repair deduplicates and sanitizes', function()
  local m = profiles.repair({active='RIFT', names={'default', 'Rift', 'rift', '../../bad', 'Farm'}})
  eq(m.active, 'rift', 'active retained')
  eq(#m.names, 3, 'no duplicates or unsafe values')
  eq(m.names[2], 'rift', 'normalized')
  eq(m.names[3], 'farm', 'third name')
  local bad = profiles.repair({active='gone', names={'Rift'}})
  eq(bad.active, 'default', 'unlisted active falls back')
end)

case('profiles: save and switch are separate operations', function()
  local m = profiles.repair(nil)
  local copy = profiles.add(m, 'Hunter')
  eq(m.active, 'default', 'original not mutated')
  eq(copy.active, 'default', 'save as does not switch')
  eq(profiles.has(copy, 'HUNTER'), true, 'case insensitive search')
  eq(profiles.add(copy, 'hunter'), nil, 'name collision')
  eq(profiles.add(copy, 'default'), nil, 'cannot overwrite default')
  local selected = profiles.activate(copy, 'hunter')
  eq(selected.active, 'hunter', 'loaded profile')
  eq(copy.active, 'default', 'original manifest unchanged')
  eq(profiles.activate(copy, 'none'), nil, 'missing name rejected')
end)
