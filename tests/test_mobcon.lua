local mobcon = require('lib.mobcon')
local settings = require('lib.settings')
local engine = require('lib.engine')
local fake = require('fake')

local function reply(player_id, target_id, faction)
  return string.pack("<I4I4I4I4I4", player_id, target_id, faction, 10, 0)
end

case("mobcon: RoF2 OP_Consider request and all nine faction replies", function()
  local factions = { "Ally", "Warmly", "Kindly", "Amiably", "Indifferent",
    "Scowling", "Threateningly", "Dubious", "Apprehensive" }
  local c = mobcon.new()
  mobcon.set_zone(c, "ecommons")
  for n, faction in ipairs(factions) do
    local bytes = mobcon.request(c, n, "a_rat", 1000 + n * 100, 200)
    eq(#bytes, 20, "exact wire request size")
    local player, target, zero1, zero2, zero3 = string.unpack("<I4I4I4I4I4", bytes)
    eq(player, 200, "packet player id")
    eq(target, n, "packet target id")
    eq(zero1 + zero2 + zero3, 0, "packet reserved bytes zero")
    check(mobcon.record_packet(c, mobcon.OPCODE, reply(200, n, n), 1100 + n * 100), "reply consumed")
    eq(mobcon.lookup(c, n, 1150 + n * 100, "a rat"), faction, "wire tier " .. n)
  end
  check(not mobcon.restricted(settings.defaults().targeting.mob_cons), "default does not query")
  check(mobcon.restricted(settings.repair({ targeting = { mob_cons = { Ally = false } } }).targeting.mob_cons),
    "excluded faction requires query")
  eq(mobcon.request(c, 0, "", 100, 200), nil, "zero target invalid")
  eq(mobcon.request(c, 1, "", 100, 0), nil, "zero player invalid")
  check(not mobcon.none_enabled(settings.defaults().targeting.mob_cons), "normal filter has options")
  local none = {}
  for _, tier in ipairs(mobcon.TIERS) do none[tier] = false end
  check(mobcon.none_enabled(none), "all disabled does not need consider")
end)

case("mobcon: only own response is hidden; bad, manual, and late replies pass through", function()
  local c = mobcon.new()
  mobcon.set_zone(c, "qeynos")
  mobcon.request(c, 7, "a rat", 1000, 21)
  check(not mobcon.record_packet(c, 0x1234, reply(21, 7, 6), 1050), "other opcode")
  check(not mobcon.record_packet(c, mobcon.OPCODE, reply(21, 8, 9), 1050), "other target")
  check(not mobcon.record_packet(c, mobcon.OPCODE, reply(22, 7, 9), 1050), "other player")
  check(not mobcon.record_packet(c, mobcon.OPCODE, "bad", 1050), "short packet")
  eq(mobcon.lookup(c, 7, 1050), nil, "not cached yet")
  check(mobcon.record_packet(c, mobcon.OPCODE, reply(21, 7, 6), 1070), "own response suppressed")
  eq(mobcon.lookup(c, 7, 1080, "a_rat"), "Scowling", "reply cached")
  check(not mobcon.record_packet(c, mobcon.OPCODE, reply(21, 7, 6), 1100), "manual repeat passes through")
  mobcon.request(c, 9, "a bat", 2000, 21)
  mobcon.cancel(c)
  check(mobcon.record_packet(c, mobcon.OPCODE, reply(21, 9, 1), 2600), "cancelled late response hidden")
  eq(mobcon.lookup(c, 9, 2650), nil, "cancelled result not cached")
  mobcon.request(c, 10, "an orc", 3000, 21)
  check(mobcon.record_packet(c, mobcon.OPCODE, reply(21, 10, 0), 3100), "unknown faction suppressed")
  eq(mobcon.lookup(c, 10, 3120), nil, "invalid faction not cached")
  mobcon.request(c, 11, "an orc", 4000, 21)
  check(mobcon.record_packet(c, mobcon.OPCODE, reply(21, 11, 1), 6100), "late reply hidden briefly")
  eq(mobcon.lookup(c, 11, 6150), nil, "late reply not cached")
  mobcon.request(c, 12, "an orc", 7000, 21)
  check(not mobcon.record_packet(c, mobcon.OPCODE, reply(21, 12, 1), 10500), "unrelated stale response passes")
end)

case("mobcon: cache is scoped, expires, checks name, and stays bounded", function()
  local c = mobcon.new()
  mobcon.set_zone(c, "qeynos")
  mobcon.request(c, 7, "a_rat", 1000, 21)
  check(mobcon.record_packet(c, mobcon.OPCODE, reply(21, 7, 2), 1040), "right response")
  eq(mobcon.lookup(c, 7, 1041, "a rat"), "Warmly", "name normalization")
  eq(mobcon.lookup(c, 8, 1041, "a rat"), nil, "same name, other id")
  eq(mobcon.lookup(c, 7, 1042, "an orc"), nil, "recycled id, different name")
  mobcon.request(c, 7, "a rat", 2000, 21)
  mobcon.record_packet(c, mobcon.OPCODE, reply(21, 7, 6), 2050)
  eq(mobcon.lookup(c, 7, 2050 + mobcon.CACHE_MS, "a rat"), nil, "expires in 10 minutes")
  for id = 1, mobcon.MAX_ENTRIES + 2 do
    mobcon.request(c, id, "mob" .. id, 9000 + id * 100, 21)
    mobcon.record_packet(c, mobcon.OPCODE, reply(21, id, 8), 9050 + id * 100)
  end
  local count = 0
  for _ in pairs(c.entries) do count = count + 1 end
  eq(count, mobcon.MAX_ENTRIES, "maximum cached entries")
  eq(mobcon.lookup(c, 1, 30000, "mob1"), nil, "oldest evicted")
  eq(mobcon.lookup(c, mobcon.MAX_ENTRIES + 2, 30000, "mob130"), "Dubious", "newest retained")
  mobcon.set_zone(c, "freeport")
  eq(mobcon.lookup(c, mobcon.MAX_ENTRIES + 2, 30000), nil, "zone change clears cache")
  eq(c.pending, nil, "zone change cancels pending")
end)

case("mobcon: hunter checks a viable candidate silently, then applies faction", function()
  local s = settings.repair({ mode = "hunter", targeting = { mob_cons = { Amiably = false } } })
  local e, io = engine.new(), fake.io()
  engine.start(e, io)
  local mob = fake.spawn({ id = 12, name = "a rat", x = 70, distance = 70 })
  local w = fake.world({ now = 100000, hunt = { mob }, spawns = { mob }, paths = { [12] = 80 } })
  w.mob_con = function(id) return id == mob.id and mob.faction_con or nil end
  engine.tick(e, w, s, io)
  eq(io.considered.id, 12, "requests faction for viable mob")
  check(not io.has("/consider"), "no chat /consider command")
  check(not io.has("/target id 12"), "does not alter target")
  check(not io.has("/nav id 12 distance=10"), "does not move before result")
  eq(e.hunt, nil, "no hunt yet")
  mob.faction_con, w.now = "Amiably", 101100
  engine.tick(e, w, s, io)
  eq(e.hunt, nil, "excluded mob not hunted")
  check(not io.has("/nav id 12 distance=10"), "no navigation to excluded NPC")
  mob.faction_con, w.now = "Scowling", 102200
  engine.tick(e, w, s, io)
  eq(e.hunt and e.hunt.id, 12, "eligible mob is hunted")
  engine.tick(e, w, s, io)
  check(io.has("/nav id 12 distance=10"), "navigates after reply")
end)

